#!/bin/bash
# Script to update registry configuration across the project

set -e

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Configuration
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
SECRETS_DIR="${PROJECT_ROOT}/secrets"
REGISTRY_CONF="${SECRETS_DIR}/registry.conf"

# Function to print colored output
print_info() {
    echo -e "${BLUE}[INFO]${NC} $1"
}

print_success() {
    echo -e "${GREEN}[SUCCESS]${NC} $1"
}

print_warning() {
    echo -e "${YELLOW}[WARNING]${NC} $1"
}

print_error() {
    echo -e "${RED}[ERROR]${NC} $1"
}

# Check if registry.conf exists
if [[ ! -f "${REGISTRY_CONF}" ]]; then
    print_error "Registry configuration not found at: ${REGISTRY_CONF}"
    print_info "Please create it first:"
    echo "  cp ${SECRETS_DIR}/registry.conf.example ${REGISTRY_CONF}"
    echo "  vi ${REGISTRY_CONF}"
    exit 1
fi

# Source the registry configuration
source "${REGISTRY_CONF}"

# Validate required variables
if [[ -z "${REGISTRY_URL}" ]] || [[ -z "${REGISTRY_ORG}" ]]; then
    print_error "REGISTRY_URL and REGISTRY_ORG must be set in ${REGISTRY_CONF}"
    exit 1
fi

FULL_REGISTRY="${REGISTRY_URL}/${REGISTRY_ORG}"

print_info "Registry Configuration:"
echo "  Registry URL: ${REGISTRY_URL}"
echo "  Organization: ${REGISTRY_ORG}"
echo "  Full Registry: ${FULL_REGISTRY}"
echo ""

# Function to update deployment files
update_deployments() {
    local deployment_file="$1"
    local image_placeholder="$2"
    local new_image="${FULL_REGISTRY}/${image_placeholder}"

    if [[ -f "${deployment_file}" ]]; then
        print_info "Updating ${deployment_file}..."
        # Update image references
        sed -i.bak "s|image: quay.io/your-org/|image: ${FULL_REGISTRY}/|g" "${deployment_file}"
        sed -i.bak "s|image: registry.example.com/your-org/|image: ${FULL_REGISTRY}/|g" "${deployment_file}"
        rm -f "${deployment_file}.bak"
        print_success "Updated ${deployment_file}"
    fi
}

# Update Kubernetes deployment files
print_info "Updating Kubernetes deployment files..."
update_deployments "${PROJECT_ROOT}/dashboard/k8s/backend-deployment.yaml" "ai-workflow-dashboard-backend"
update_deployments "${PROJECT_ROOT}/dashboard/k8s/frontend-deployment.yaml" "ai-workflow-dashboard-frontend"

# Update Helm values if needed
if [[ -d "${PROJECT_ROOT}/helm/ai-document-pipeline" ]]; then
    print_info "Updating Helm chart values..."

    # Create a custom values file for registry overrides
    cat > "${PROJECT_ROOT}/helm/ai-document-pipeline/values-registry.yaml" << EOF
# Registry configuration override
# Generated by update-registry-config.sh
# DO NOT EDIT MANUALLY - This file is auto-generated

global:
  imageRegistry: ${REGISTRY_URL}
  imagePullSecrets: []

# Custom image configurations can be added here
# Example:
# dashboard:
#   backend:
#     image:
#       repository: ${FULL_REGISTRY}/ai-workflow-dashboard-backend
#       tag: latest
#   frontend:
#     image:
#       repository: ${FULL_REGISTRY}/ai-workflow-dashboard-frontend
#       tag: latest
EOF

    print_success "Created values-registry.yaml for Helm deployments"
    print_info "Use with: helm install -f values-registry.yaml ..."
fi

# Show summary
echo ""
print_success "Registry configuration updated successfully!"
echo ""
echo "Next steps:"
echo "1. Build images with: make build-images"
echo "2. Push images with: make push-images"
echo "3. Deploy with updated registry: make deploy"
echo ""
echo "To verify configuration: make registry-info"
